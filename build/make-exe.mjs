/**
 * Builds a standalone executable.
 *
 * Three steps, using only what Node ships with plus esbuild:
 *
 *   1. Bundle the whole TypeScript source into a single CommonJS file.
 *      Node's Single Executable Application format requires one CJS entry —
 *      it has no module resolver inside the binary.
 *   2. Generate the SEA blob (`node --experimental-sea-config`).
 *   3. Copy a Node runtime and inject the blob into it with postject.
 *
 * Cross-compiling is possible because step 3 is just binary surgery on the
 * target platform's `node` executable: a Windows .exe can be produced from
 * Linux by downloading the official `node.exe` and injecting into that.
 *
 *   node build/make-exe.mjs                 # host platform
 *   node build/make-exe.mjs --target win     # Windows .exe
 *   node build/make-exe.mjs --target all
 */

import { execFileSync } from 'node:child_process';
import { chmodSync, copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { createWriteStream } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { pipeline } from 'node:stream/promises';
import { Readable } from 'node:stream';

import * as esbuild from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'dist-exe');
const workDir = join(outDir, '.vinna');
const cacheDir = join(root, '.node-cache');

/**
 * Node runtime used for the packaged binaries.
 *
 * Defaults to the version running this script. That is not laziness — the SEA
 * blob is produced by the local `node --experimental-sea-config`, and a blob
 * generated by one Node version is not reliably readable by another. A
 * mismatch fails at startup with an opaque V8 error, so the versions are
 * pinned together by construction.
 */
const NODE_VERSION = process.env.RTH_NODE_VERSION || process.version;

const TARGETS = {
  win: {
    label: 'Windows (x64)',
    output: 'RafraenThjonusta.exe',
    url: `https://nodejs.org/dist/${NODE_VERSION}/win-x64/node.exe`,
    archive: false,
    // Windows binaries are signed; postject must not corrupt the signature
    // table, so the resource is placed in a dedicated PE section.
    extra: [],
  },
  linux: {
    label: 'Linux (x64)',
    output: 'rafraen-thjonusta',
    url: `https://nodejs.org/dist/${NODE_VERSION}/node-${NODE_VERSION}-linux-x64.tar.gz`,
    archive: 'tar',
    innerPath: `node-${NODE_VERSION}-linux-x64/bin/node`,
    extra: [],
  },
  mac: {
    label: 'macOS (arm64)',
    output: 'RafraenThjonusta',
    url: `https://nodejs.org/dist/${NODE_VERSION}/node-${NODE_VERSION}-darwin-arm64.tar.gz`,
    archive: 'tar',
    innerPath: `node-${NODE_VERSION}-darwin-arm64/bin/node`,
    // macOS refuses to run a binary whose existing signature no longer matches.
    extra: ['--macho-segment-name', 'NODE_SEA'],
  },
};

function log(message) {
  process.stdout.write(`${message}\n`);
}

function step(n, total, message) {
  log(`\n[${n}/${total}] ${message}`);
}

function humanSize(bytes) {
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
}

// ---------------------------------------------------------------------------
// 1. Bundle
// ---------------------------------------------------------------------------

async function bundle() {
  const outfile = join(workDir, 'rafraen.cjs');

  await esbuild.build({
    entryPoints: [join(root, 'src/desktop/main.ts')],
    bundle: true,
    platform: 'node',
    target: 'node22',
    format: 'cjs',
    outfile,
    minify: false, // keeps stack traces readable when a user reports a problem
    sourcemap: false,
    legalComments: 'none',
    // Node builtins stay external; everything of ours is inlined.
    external: ['node:*'],
    define: { 'import.meta.url': '__filename' },
    logLevel: 'warning',
  });

  const size = statSync(outfile).size;
  log(`    Bundlað: ${humanSize(size)}`);
  return outfile;
}

// ---------------------------------------------------------------------------
// 2. SEA blob
// ---------------------------------------------------------------------------

function buildBlob(entryFile) {
  const configPath = join(workDir, 'sea-config.json');
  const blobPath = join(workDir, 'rafraen.blob');

  writeFileSync(
    configPath,
    JSON.stringify(
      {
        main: entryFile,
        output: blobPath,
        disableExperimentalSEAWarning: true,
        // Snapshots would start faster but do not support every builtin we use.
        useSnapshot: false,
        useCodeCache: false,
      },
      null,
      2,
    ),
  );

  execFileSync(process.execPath, ['--experimental-sea-config', configPath], { stdio: 'inherit' });
  log(`    Blob: ${humanSize(statSync(blobPath).size)}`);
  return blobPath;
}

// ---------------------------------------------------------------------------
// 3. Runtime download and injection
// ---------------------------------------------------------------------------

async function download(url, destination) {
  if (existsSync(destination)) {
    log(`    Í skyndiminni: ${destination.replace(root, '.')}`);
    return destination;
  }

  log(`    Sæki ${url}`);
  const response = await fetch(url);
  if (!response.ok || !response.body) {
    throw new Error(`Niðurhal mistókst (${response.status}) — ${url}`);
  }

  mkdirSync(dirname(destination), { recursive: true });
  await pipeline(Readable.fromWeb(response.body), createWriteStream(destination));
  log(`    Sótt: ${humanSize(statSync(destination).size)}`);
  return destination;
}

async function fetchRuntime(target, key) {
  if (!target.archive) {
    const cached = join(cacheDir, `node-${NODE_VERSION}-${key}.bin`);
    return download(target.url, cached);
  }

  const archivePath = join(cacheDir, `node-${NODE_VERSION}-${key}.tar.gz`);
  await download(target.url, archivePath);

  const extracted = join(cacheDir, `node-${NODE_VERSION}-${key}.bin`);
  if (!existsSync(extracted)) {
    execFileSync('tar', ['-xzf', archivePath, '-C', cacheDir, target.innerPath], { stdio: 'inherit' });
    copyFileSync(join(cacheDir, target.innerPath), extracted);
  }
  return extracted;
}

async function inject(target, key, blobPath) {
  const runtime = await fetchRuntime(target, key);
  const output = join(outDir, target.output);

  copyFileSync(runtime, output);
  chmodSync(output, 0o755);

  // postject ships a CLI; running it through the local install avoids
  // depending on a global npx cache.
  const postject = join(root, 'node_modules', 'postject', 'dist', 'cli.js');
  execFileSync(
    process.execPath,
    [
      postject,
      output,
      'NODE_SEA_BLOB',
      blobPath,
      '--sentinel-fuse',
      'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2',
      ...target.extra,
    ],
    { stdio: 'inherit' },
  );

  log(`    ✔ ${target.label}: dist-exe/${target.output} (${humanSize(statSync(output).size)})`);
  return output;
}

// ---------------------------------------------------------------------------

async function run() {
  const argIndex = process.argv.indexOf('--target');
  const requested = argIndex >= 0 ? process.argv[argIndex + 1] : hostTarget();

  const keys =
    requested === 'all'
      ? Object.keys(TARGETS)
      : String(requested).split(',').map((value) => value.trim());

  for (const key of keys) {
    if (!TARGETS[key]) {
      throw new Error(`Óþekkt markmið "${key}". Veldu: ${Object.keys(TARGETS).join(', ')}, all`);
    }
  }

  log('Smíða keyrsluskrá fyrir Rafræna Þjónustu');
  log(`Node-útgáfa: ${NODE_VERSION}`);

  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(workDir, { recursive: true });
  mkdirSync(cacheDir, { recursive: true });

  const total = 2 + keys.length;
  step(1, total, 'Bundla forritið í eina skrá');
  const entryFile = await bundle();

  step(2, total, 'Búa til SEA-blob');
  const blobPath = buildBlob(entryFile);

  const built = [];
  for (const [index, key] of keys.entries()) {
    step(3 + index, total, `Smíða keyrsluskrá — ${TARGETS[key].label}`);
    built.push(await inject(TARGETS[key], key, blobPath));
  }

  writeFileSync(join(outDir, 'LESTU-MIG.txt'), readmeText(), 'utf8');
  rmSync(workDir, { recursive: true, force: true });

  log('\nTilbúið.');
  for (const path of built) log(`  ${path}`);
  log('');
}

function hostTarget() {
  if (process.platform === 'win32') return 'win';
  if (process.platform === 'darwin') return 'mac';
  return 'linux';
}

function readmeText() {
  return [
    'Rafræn Þjónusta',
    '===============',
    '',
    'Tvísmelltu á RafraenThjonusta.exe.',
    '',
    'Forritið ræsir sig, opnar vafrann og sýnir stjórnborðið. Í fyrsta skipti',
    'býrðu til aðganginn þinn beint í vafranum — engin uppsetning þarf.',
    '',
    'Gögn eru geymd hjá þér:',
    '  Windows   %APPDATA%\\RafraenThjonusta',
    '  macOS     ~/Library/Application Support/RafraenThjonusta',
    '  Linux     ~/.local/share/rafraen-thjonusta',
    '',
    'Þar er gagnagrunnurinn (rafraen.sqlite), myndaðar vefsíður og',
    'stillingaskráin. Taktu afrit af þessari möppu reglulega.',
    '',
    'Til að stöðva forritið: lokaðu svarta glugganum.',
    '',
    'Windows SmartScreen',
    '-------------------',
    'Þar sem skráin er ekki undirrituð með kóðaskírteini gæti Windows sýnt',
    'viðvörun í fyrsta skipti. Veldu "More info" og svo "Run anyway".',
    'Til að losna við það þarf kóðaundirritunarskírteini (Authenticode).',
    '',
  ].join('\n');
}

run().catch((error) => {
  log(`\nSmíði mistókst: ${error.message}`);
  process.exit(1);
});
